function heavyWidth(text, size, track = 7) { let w = 0; for (let i = 0; i < text.length; i++) { const c = text[i]; w += (c === ' ' ? 30 : (HEAVY[c] || HEAVY['-'])[0]) + (i < text.length - 1 ? track : 0); } return w * size / 100; }

// o: {align, track, skew, fill, layers:[[color, px]...] outermost first, drop:[dx,dy,color], letter(i,n)->{dx,dy,s,rot,a,fill}, rot}
function heavyText(g, text, x, y, size, o = {}) {
  text = text.toUpperCase();
  const track = o.track === undefined ? 7 : o.track, k = size / 100, total = heavyWidth(text, size, track);
  let cx = o.align === 'left' ? 0 : o.align === 'right' ? -total : -total / 2;
  const letters = [];
  for (let i = 0; i < text.length; i++) {
    const c = text[i]; const gl = c === ' ' ? null : (HEAVY[c] || HEAVY['-']);
    const w = c === ' ' ? 30 : gl[0];
    if (gl) letters.push({ gl, x: cx, w: w * k, i });
    cx += (w + track) * k;
  }
  g.save(); g.translate(x, y); if (o.rot) g.rotate(o.rot); g.transform(1, 0, -(o.skew || 0), 1, (o.skew || 0) * 0, 0);
  const n = text.length;
  const place = (L, fn) => {
    const m = o.letter ? o.letter(L.i, n) : null; if (m && m.a !== undefined && m.a <= 0.001) return;
    g.save(); g.translate(L.x + L.w / 2 + (m ? m.dx || 0 : 0), (m ? m.dy || 0 : 0));
    if (m) { if (m.rot) g.rotate(m.rot); if (m.s !== undefined) g.scale(m.s, m.s); if (m.a !== undefined) g.globalAlpha *= clamp(m.a); }
    g.beginPath();
    for (let ci = 1; ci < L.gl.length; ci++) { const ct = L.gl[ci]; ct.forEach((p, j) => { const px = (p[0] - L.gl[0] / 2) * k, py = (p[1] - 50) * k; j ? g.lineTo(px, py) : g.moveTo(px, py); }); g.closePath(); }
    fn(m); g.restore();
  };
  g.lineJoin = 'miter'; g.miterLimit = 2.2;
  if (o.drop) { for (const L of letters) place(L, () => { g.translate(o.drop[0], o.drop[1]); const mw = o.layers && o.layers.length ? o.layers[0][1] : 0; g.fillStyle = o.drop[2]; g.strokeStyle = o.drop[2]; g.lineWidth = mw * 2; if (mw) g.stroke(); g.fill('evenodd'); }); }
  for (const [col, wpx] of (o.layers || [])) for (const L of letters) place(L, () => { g.strokeStyle = col; g.lineWidth = wpx * 2; g.stroke(); });
  for (const L of letters) place(L, m => {
    let f = (m && m.fill) || o.fill || '#fff';
    if (Array.isArray(f)) { const gr = g.createLinearGradient(0, -size / 2, 0, size / 2); f.forEach(([s, c]) => gr.addColorStop(s, c)); f = gr; }
    g.fillStyle = f; g.fill('evenodd');
  });
  g.restore();
  return total;
}

