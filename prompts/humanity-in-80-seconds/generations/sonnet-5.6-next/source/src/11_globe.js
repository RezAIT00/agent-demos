  // view with (lon0, lat0) facing the camera
  function view(lon0, lat0, cx, cy, radius, city = 0) {
    const cl = Math.cos(lon0 * D), sl = Math.sin(lon0 * D), cp = Math.cos(lat0 * D), sp = Math.sin(lat0 * D);
    const rot = (v) => {
      const x = v[0] * cl - v[2] * sl, z = v[0] * sl + v[2] * cl;
      return [x, v[1] * cp - z * sp, v[1] * sp + z * cp];
    };
    const c0 = rot([1, 0, 0]), c1 = rot([0, 1, 0]), c2 = rot([0, 0, 1]);
    const project = (v) => { const q = rot(v); return { x: cx + q[0] * radius, y: cy - q[1] * radius, z: q[2] }; };
    return {
      cx, cy, r: radius, city, mat: [...c0, ...c1, ...c2], rot,
      project, at: (lon, lat) => project(vec(lon, lat)),
    };
  }
  function slerp(a, b, k) {
    const dot = clamp(a[0] * b[0] + a[1] * b[1] + a[2] * b[2], -1, 1), om = Math.acos(dot);
    if (om < 1e-5) return a;
    const s0 = Math.sin((1 - k) * om) / Math.sin(om), s1 = Math.sin(k * om) / Math.sin(om);
    return [a[0] * s0 + b[0] * s1, a[1] * s0 + b[1] * s1, a[2] * s0 + b[2] * s1];
  }
  // densify waypoints along great circles
  function route(pts, seed = 1) {
    const vs = P(pts).map(([lo, la]) => vec(lo, la));
    const out = [];
    for (let i = 0; i + 1 < vs.length; i++) {
      const ang = Math.acos(clamp(vs[i][0] * vs[i + 1][0] + vs[i][1] * vs[i + 1][1] + vs[i][2] * vs[i + 1][2], -1, 1));
      const n = Math.max(2, Math.ceil(ang / (1.2 * D)));
      for (let k = 0; k < n; k++) out.push(slerp(vs[i], vs[i + 1], k / n));
    }
    out.push(vs[vs.length - 1]);
    // small hearths that light up around the way
    const r = rng(seed * 97 + 5), hearths = [];
    for (let i = 3; i < out.length; i++) {
      for (let k = 0; k < 2; k++) {
        if (r() > 0.62) continue;
        const v = out[i], j = [v[0] + (r() - 0.5) * 0.10, v[1] + (r() - 0.5) * 0.10, v[2] + (r() - 0.5) * 0.10];
        const m = hypot(...j);
        hearths.push({ v: [j[0] / m, j[1] / m, j[2] / m], at: i / (out.length - 1) + r() * 0.10, s: r() });
      }
    }
    return { pts: out, hearths };
  }
  // draw a golden thread from its start up to fraction k, with a bright head
